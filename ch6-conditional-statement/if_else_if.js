let score = 85;

if (score >= 90) {
    console.log(`Your score is ${score}. Grade: A`);
} else if (score >= 80) {
    console.log(`Your score is ${score}. Grade: B`);
} else if (score >= 70) {
    console.log(`Your score is ${score}. Grade: C`);
} else if (score >= 60) {
    console.log(`Your score is ${score}. Grade: D`);
} else {
    console.log(`Your score is ${score}. Grade: F`);
}